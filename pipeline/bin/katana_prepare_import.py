#!/usr/bin/env python3
"""Verify a portable bundle and bind it to the destination machine's Katana."""
from __future__ import annotations

import argparse
import csv
import json
import shutil
from pathlib import Path

from katana_bundle import SCHEMA, inside, sha256, write_csv

IMPORT_VIEW_SCHEMA = "katana-import-views/v1"


def write_config(path: Path, payload: dict) -> None:
    if path.is_symlink():
        raise ValueError(f"Refusing to replace a linked Katana config: {path}")
    if path.exists():
        try:
            old = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, OSError) as error:
            raise ValueError("Refusing to replace an existing user-edited Katana config") from error
        if old.get("generated_by") != SCHEMA:
            raise ValueError("Refusing to replace a Katana config not generated by this bundle initializer")
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def native_view_file(source: Path, destination: Path) -> None:
    """Reuse genuine bytes; never derive, rename columns, filter or recompute rows."""
    if destination.exists():
        if not destination.is_file() or destination.stat().st_size != source.stat().st_size or sha256(destination) != sha256(source):
            raise ValueError(f"Existing import-view native file differs; preserved: {destination}")
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    # Separate bytes prevent a later edit of a view from mutating the master.
    # Shared references, BAMs and quantification still use absolute master paths.
    shutil.copyfile(source, destination)
    if sha256(source) != sha256(destination):
        raise ValueError(f"Import-view native bytes differ from master: {destination}")


def prepare_views(root: Path, manifest: dict, payload: dict) -> dict:
    """Separate reciprocal contrasts for the unchanged scanner's alias rules."""
    views_root = root.parent / f"{root.name}_katana_import_views"
    if views_root.resolve() != views_root:
        raise ValueError("Refusing to use a linked import-view root")
    if views_root.is_relative_to(root) or root.is_relative_to(views_root):
        raise ValueError("Import views must be separate from the immutable master bundle")
    output_root = Path(payload["output_root"])
    if views_root.is_relative_to(output_root) or output_root.is_relative_to(views_root):
        raise ValueError("Katana output directory must be separate from the import views")
    with (root / "pipeline_info/contrastsheet.valid.csv").open(encoding="utf-8-sig", newline="") as handle:
        contrasts = list(csv.DictReader(handle))
    manifest_hash = sha256(root / "manifest.json")
    index_path = inside(views_root, "import_views.json")
    if index_path.is_symlink():
        raise ValueError("Refusing to replace a linked import-view index")
    if views_root.exists() and not index_path.is_file():
        raise ValueError("Refusing to use an existing import-view directory without a generated index")
    if index_path.exists():
        old = json.loads(index_path.read_text(encoding="utf-8"))
        if old.get("schema") != IMPORT_VIEW_SCHEMA or old.get("source_bundle") != str(root) or old.get("manifest_sha256") != manifest_hash:
            raise ValueError("Existing import-view index belongs to another master; preserved")
    views = []
    for comparison in payload["comparisons"]:
        cid = comparison["comparison_id"]
        view = inside(views_root, cid)
        if view.resolve() != view:
            raise ValueError(f"Refusing to use a linked comparison import view: {cid}")
        selected = [row for row in contrasts if row["contrast"] == cid]
        if len(selected) != 1:
            raise ValueError(f"Import view needs exactly one existing declared contrast: {cid}")
        for artifact in manifest["artifacts"]:
            if artifact.get("comparison_id") == cid and artifact["kind"] in {"rmats", "deg"} and artifact.get("status", "").startswith("available"):
                native_view_file(inside(root, artifact["relative_path"]), inside(view, artifact["relative_path"]))
        sheet = inside(view, "pipeline_info/contrastsheet.valid.csv")
        if sheet.is_symlink():
            raise ValueError("Refusing to replace a linked import-view contrastsheet")
        write_csv(sheet, selected, ["contrast", "treatment", "control"])
        config = json.loads(json.dumps(payload))
        config["input_paths"].update(rmats_root=str(view / "rmats"), deg_root=str(view / "DEG"), contrastsheet_path=str(sheet))
        # The unchanged model parses source names before explicit group fields.
        # A reversed native source must retain its source-oriented name so the
        # corresponding reversal flag produces the declared final direction.
        # Paths remain the unchanged contrast-ID files discovered in this view.
        native_comparison = dict(comparison,
                                 rmats_name=comparison["rmats_name"] if comparison["reverse_splicing"] else cid,
                                 deg_name=comparison["deg_name"] if comparison["reverse_deg"] else cid)
        config.update(comparisons=[native_comparison], selected_comparison_ids=[cid], comparison_order_ids=[cid],
                      output_root=str(Path(payload["output_root"]) / cid), source_bundle_root=str(root),
                      import_view_schema=IMPORT_VIEW_SCHEMA, import_view_comparison_id=cid)
        config_path = inside(view, ".katana_project.yaml")
        write_config(config_path, config)
        views.append({"comparison_id": cid, "root": str(view), "config": str(config_path), "config_sha256": sha256(config_path),
                      "treatment": comparison["experiment_group"], "control": comparison["control_group"],
                      "native_sources": "unchanged rMATS/DEG bytes; shared quantification, counts, references and remaining native branches in master"})
    index = {"schema": IMPORT_VIEW_SCHEMA, "source_bundle": str(root), "manifest_sha256": manifest_hash,
             "reason": "Original Katana scanner treats reciprocal names as aliases; each context retains its declared direction and native sources",
             "views": views, "master_statistics_changed": False, "original_katana_changed": False}
    index_path.write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return {"generated_by": SCHEMA, "import_mode": "per_comparison_views", "source_bundle": str(root),
            "view_index": str(index_path), "import_views": views, "status": "ready_for_review"}


def verify_bundle(root: Path) -> dict:
    root = root.resolve()
    manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("schema") != SCHEMA:
        raise ValueError("Directory is not an independently generated Katana pipeline bundle")
    expected_sums = {}
    for line in (root / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        digest, relative = line.split("  ", 1)
        if relative in expected_sums:
            raise ValueError(f"Duplicate checksum entry: {relative}")
        expected_sums[relative] = digest
    if expected_sums.get("manifest.json") != sha256(root / "manifest.json"):
        raise ValueError("Bundle manifest failed integrity verification")
    for artifact in manifest["artifacts"]:
        if not artifact.get("status", "").startswith("available"):
            continue
        path = inside(root, artifact["relative_path"])
        if expected_sums.get(artifact["relative_path"]) != artifact["sha256"] or not path.is_file() or path.stat().st_size != artifact["bytes"] or sha256(path) != artifact["sha256"]:
            raise ValueError(f"Bundle artifact failed integrity verification: {artifact['relative_path']}")
    return manifest


def prepare_import(root: Path, output_root: Path | None = None, mode: str = "JC", verify_only: bool = False) -> dict:
    root = root.resolve()
    manifest = verify_bundle(root)
    if verify_only:
        return {"verified": True, "bundle": str(root), "status": manifest["status"]}
    if mode not in {"JC", "JCEC"}:
        raise ValueError("rMATS mode must be JC or JCEC")
    config_path = root / ".katana_project.yaml"
    if config_path.exists():
        try:
            old = json.loads(config_path.read_text(encoding="utf-8"))
        except (ValueError, OSError) as error:
            raise ValueError("Refusing to replace an existing user-edited Katana config") from error
        if old.get("generated_by") != SCHEMA:
            raise ValueError("Refusing to replace a Katana config not generated by this bundle initializer")
    artifacts = [row for row in manifest["artifacts"] if row.get("status", "").startswith("available")]
    by_kind: dict[str, list[dict]] = {}
    for artifact in artifacts:
        by_kind.setdefault(artifact["kind"], []).append(artifact)
    input_paths = {"rmats_root": str(root / "rmats"), "contrastsheet_path": str(root / "pipeline_info/contrastsheet.valid.csv")}
    for kind, key in (("deg", "deg_root"), ("quant", "quant_root"), ("dexseq", "dexseq_root"), ("dtu", "dtu_root"), ("suppa", "suppa_root")):
        if by_kind.get(kind):
            # File locations are standardized beneath one category root.
            relative = Path(by_kind[kind][0]["relative_path"])
            input_paths[key] = str(root / relative.parts[0])
    for kind, key in (("normalized_counts", "counts_path"), ("annotation", "annotation_tsv")):
        if by_kind.get(kind):
            if len(by_kind[kind]) != 1:
                raise ValueError(f"Bundle must contain exactly one {kind} file")
            input_paths[key] = str(inside(root, by_kind[kind][0]["relative_path"]))
    tool_paths = {}
    for kind in ("gtf", "genome_fasta", "transcript_fasta", "annotation"):
        if by_kind.get(kind):
            tool_paths["annotation_tsv" if kind == "annotation" else kind] = str(inside(root, by_kind[kind][0]["relative_path"]))
    if by_kind.get("bam"):
        tool_paths["bam_root"] = str(root / Path(by_kind["bam"][0]["relative_path"]).parts[0])
    comparisons = []
    for row in manifest["comparisons"]:
        comparison_id = row["comparison_id"]
        treatment, control = row["treatment"], row["control"]
        comparison = {"comparison_id": comparison_id, "display_name": f"{treatment} vs {control}",
                      "experiment_group": treatment, "control_group": control,
                      "source_experiment_group": row["rmats_group1"], "source_control_group": row["rmats_group2"],
                      "source_direction": "experiment_vs_control", "analysis_direction": "experiment_vs_control",
                      "reverse_direction": False, "reverse_splicing": row["rmats_group1"] != treatment,
                      "reverse_deg": row["deg_target"] != treatment}
        for kind in ("rmats", "deg", "dexseq", "dtu", "suppa"):
            matches = [item for item in by_kind.get(kind, []) if item.get("comparison_id") == comparison_id]
            if matches:
                relative = Path(matches[0]["relative_path"])
                if kind == "rmats":
                    comparison["rmats_name"] = f"{row['rmats_group1']}_vs_{row['rmats_group2']}"
                elif kind == "deg":
                    comparison["deg_name"] = f"{row['deg_target']}_vs_{row['deg_reference']}"
                else:
                    comparison[f"{kind}_name"] = comparison_id
        comparisons.append(comparison)
    sample_lookup = {sample["sample_id"]: sample for sample in manifest["samples"]}
    isoform_samples = [{"sample_id": item["sample_id"], "quant_sf": str(inside(root, item["relative_path"])),
                        "sample_group": sample_lookup[item["sample_id"]]["condition"], "condition": sample_lookup[item["sample_id"]]["condition"],
                        "batch": sample_lookup[item["sample_id"]].get("batch"), "include": True} for item in by_kind.get("quant", [])]
    destination_output = (output_root or root.parent / f"{root.name}_katana_output").resolve()
    if destination_output.is_relative_to(root) or root.is_relative_to(destination_output):
        raise ValueError("Katana output directory must be separate from the immutable input bundle")
    payload = {"generated_by": SCHEMA, "selected_rmats_mode": mode, "output_root": str(destination_output),
               "input_paths": input_paths, "tool_paths": tool_paths, "comparisons": comparisons, "isoform_samples": isoform_samples,
               "selected_comparison_ids": [row["comparison_id"] for row in comparisons], "comparison_order_ids": [row["comparison_id"] for row in comparisons],
               "confirmed": False, "pairing_confirmed": False, "comparison_sets_confirmed": False, "visualization_groups_confirmed": False}
    # Reciprocal group pairs are unconditionally merged as aliases by the
    # current scanner before and after applying saved configuration. Preserve
    # all native master results and expose independent directional contexts.
    group_pairs = [frozenset((row["treatment"], row["control"])) for row in manifest["comparisons"]]
    if len(group_pairs) != len(set(group_pairs)):
        return prepare_views(root, manifest, payload)
    # JSON is a YAML 1.2 subset and loads through current Katana's yaml.safe_load.
    write_config(config_path, payload)
    return payload


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle", type=Path, required=True)
    parser.add_argument("--output-root", type=Path)
    parser.add_argument("--rmats-mode", choices=("JC", "JCEC"), default="JC")
    parser.add_argument("--verify-only", action="store_true")
    args = parser.parse_args(argv)
    try:
        result = prepare_import(args.bundle, args.output_root, args.rmats_mode, args.verify_only)
    except (ValueError, OSError, KeyError) as error:
        parser.exit(2, f"Bundle preparation failed: {error}\n")
    print(json.dumps({"verified": True, "config": None if args.verify_only or result.get("import_views") else str(args.bundle.resolve() / '.katana_project.yaml'),
                      "import_views": result.get("import_views", []), "view_index": result.get("view_index"), "status": result.get("status", "ready_for_review")}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
