"""Build a relocatable Linux controller without using a host Python environment.

The host Python runs this build script only. The resulting archive contains its
own CPython, installed Katana dependencies and a pinned Nextflow distribution.
Java 17+ and the site's scheduler/container engine remain host prerequisites.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile
import urllib.request

PYTHON_URL = 'https://github.com/astral-sh/python-build-standalone/releases/download/20261026/cpython-3.12.16%2B20261026-x86_64-unknown-linux-gnu-install_only.tar.gz'
PYTHON_SHA = '6a79e922e50006b601f29e688407659da1c2b86ebcd4e9c7254cf234be8b89de'
NEXTFLOW_URL = 'https://github.com/nextflow-io/nextflow/releases/download/v25.10.4/nextflow-25.10.4-dist'
NEXTFLOW_SHA = '60db869a7618783e3ee60183a2b0c6c50ffc67221eabec60800b904991786aaa'


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def download(url, target, expected):
    urllib.request.urlretrieve(url, target)
    if sha(target) != expected:
        raise ValueError('Downloaded checksum mismatch: ' + target.name)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--wheel', type=Path, required=True)
    ap.add_argument('--constraints', type=Path, required=True)
    ap.add_argument('--outdir', type=Path, required=True)
    ap.add_argument('--scratch-dir', type=Path, default=Path('/tmp'))
    args = ap.parse_args()
    out = args.outdir.resolve()
    out.mkdir(parents=True, exist_ok=False)
    wheel = args.wheel.resolve(strict=True)
    constraints = args.constraints.resolve(strict=True)
    env = dict(os.environ, PYTHONNOUSERSITE='1', PYTHONDONTWRITEBYTECODE='1',
               PIP_DISABLE_PIP_VERSION_CHECK='1', PIP_NO_CACHE_DIR='1')
    for key in ('PYTHONPATH', 'PYTHONHOME', 'VIRTUAL_ENV', 'CONDA_PREFIX',
                'PIP_TARGET', 'PIP_PREFIX', 'PIP_CONSTRAINT'):
        env.pop(key, None)
    def run(command, **kw):
        subprocess.run([str(x) for x in command], check=True, env=env, **kw)
    with tempfile.TemporaryDirectory(prefix='katana-controller-', dir=args.scratch_dir) as temporary:
        work = Path(temporary)
        bundle = work / 'katana-controller'
        bundle.mkdir()
        archive = work / 'python.tar.gz'
        download(PYTHON_URL, archive, PYTHON_SHA)
        with tarfile.open(archive) as tf:
            tf.extractall(bundle, filter='data')
        python = bundle / 'python/bin/python3'
        run([python, '-I', '-m', 'pip', 'install', '--no-compile', '--no-cache-dir',
             '--constraint', constraints, str(wheel) + '[flow]'])
        run([python, '-I', '-m', 'pip', 'check'])
        (bundle / 'bin').mkdir()
        (bundle / 'lib').mkdir()
        download(NEXTFLOW_URL, bundle / 'lib/nextflow-25.10.4-dist', NEXTFLOW_SHA)
        root_script = 'root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)\n'
        launcher = ('#!/bin/sh\nset -eu\n' + root_script +
                    'export PATH="$root/bin:$PATH"\n' +
                    'exec "$root/python/bin/python3" -I -B -m katana_next.flow.cli "$@"\n')
        (bundle / 'bin/katana-flow').write_text(launcher)
        (bundle / 'bin/nextflow').write_text(
            '#!/bin/sh\nset -eu\n' + root_script +
            'if [ -n "${NXF_JAVA_HOME:-${JAVA_HOME:-}}" ]; then\n'
            '  java="${NXF_JAVA_HOME:-$JAVA_HOME}/bin/java"\n'
            'else java=java; fi\n'
            'exec "$java" --add-opens=java.base/java.lang=ALL-UNNAMED '
            '--add-opens=java.base/java.util=ALL-UNNAMED '
            '-cp "$root/lib/nextflow-25.10.4-dist" nextflow.cli.Launcher "$@"\n')
        for p in (bundle / 'bin').iterdir():
            p.chmod(0o755)
        # Console scripts generated by pip contain absolute build paths. All
        # supported entry points use a relative, installed-metadata dispatcher.
        dispatcher = bundle / 'lib/entrypoint.py'
        dispatcher.write_text('import sys\nfrom importlib.metadata import entry_points\n'
                              'name=sys.argv.pop(1)\n'
                              'ep=next(e for e in entry_points(group="console_scripts") if e.name==name)\n'
                              'sys.exit(ep.load()())\n')
        for p in (bundle / 'python/bin').iterdir():
            if p.is_file() and not p.is_symlink() and p.read_bytes()[:2] == b'#!':
                first = p.open('rb').readline()
                if str(work).encode() in first:
                    name = p.name
                    p.write_text('#!/bin/sh\nset -eu\n'
                                 'root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)\n'
                                 'exec "$root/python/bin/python3" -I -B "$root/lib/entrypoint.py" '
                                 + repr(name) + ' "$@"\n')
                    p.chmod(0o755)
        for p in bundle.rglob('direct_url.json'):
            data = json.loads(p.read_text())
            if data.get('url', '').startswith('file:'):
                p.unlink()  # optional installer provenance; replace with hashed public manifest
        for p in bundle.rglob('__pycache__'):
            shutil.rmtree(p)
        run([bundle / 'bin/katana-flow', 'export-pipeline', '--outdir', bundle / 'pipeline'])
        with (bundle / 'installed-packages.json').open('w') as stream:
            run([python, '-I', '-m', 'pip', 'list', '--format=json'], stdout=stream)
        metadata = dict(schema='katana.portable_controller/v1', wheel=wheel.name,
                        wheel_sha256=sha(wheel), python_url=PYTHON_URL, python_sha256=PYTHON_SHA,
                        nextflow_url=NEXTFLOW_URL, nextflow_sha256=NEXTFLOW_SHA,
                        constraints_sha256=sha(constraints), host_dependencies=['Java 17+', 'scheduler and container engine for the selected profile'],
                        scientific_environment='Matching task containers', science_data_used=False)
        (bundle / 'CONTROLLER_MANIFEST.json').write_text(json.dumps(metadata, indent=2) + '\n')
        # Move the installed tree before verifying: stale absolute shebangs,
        # host site-packages and editable checkout imports must not be required.
        relocated = work / 'relocated/katana-controller'
        relocated.parent.mkdir()
        bundle.rename(relocated)
        with (out / 'validation.log').open('w') as log:
            for command in ([relocated / 'python/bin/python3', '-I', '-m', 'pip', 'check'],
                            [relocated / 'bin/katana-flow', 'run', '--help'],
                            [relocated / 'bin/nextflow', '-version']):
                run(command, stdout=log, stderr=subprocess.STDOUT)
        for p in relocated.rglob('*'):
            if p.is_symlink() and not p.resolve().is_relative_to(relocated):
                raise ValueError('External runtime symlink: ' + str(p))
        archive_out = out / ('katana-controller-' + wheel.name.split('-')[1] + '-linux-x86_64.tar.gz')
        with tarfile.open(archive_out, 'w:gz', compresslevel=4) as tf:
            tf.add(relocated, arcname='katana-controller')
        metadata.update(status='built_and_relocation_checked', filename=archive_out.name,
                        archive_sha256=sha(archive_out), bytes=archive_out.stat().st_size,
                        native_controller_handoff='pending')
        (out / 'build.receipt.json').write_text(json.dumps(metadata, indent=2) + '\n')


if __name__ == '__main__':
    main()
